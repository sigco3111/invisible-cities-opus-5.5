import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
const t0 = Date.now();
await page.goto('http://127.0.0.1:5199/');
await page.waitForFunction(() => !document.getElementById('enter')?.disabled, null, { timeout: 300000 });
console.log('load ms', Date.now() - t0);
await page.click('#enter');
await page.waitForTimeout(6000);
const fps = () => page.evaluate(() => new Promise((r) => { let n = 0; const s = performance.now(); const f = () => { n++; if (performance.now() - s < 3000) requestAnimationFrame(f); else r({ fps: n / 3, calls: window.__app.renderer.info.render.calls, tris: window.__app.renderer.info.render.triangles }); }; requestAnimationFrame(f); }));
console.log('overview', await fps());
await page.evaluate(() => window.__app.focusCity(25));
await page.waitForTimeout(4000);
console.log('focus octavia', await fps());
console.log(errs.slice(0, 10).join('\n'));
await browser.close();
